type schemaDocument struct {
	Paths      map[string]pathItem `yaml:"paths"`
	Components struct {
		Schemas    map[string]schemaNode    `yaml:"schemas"`
		Parameters map[string]parameterNode `yaml:"parameters"`
	} `yaml:"components"`
}

type pathItem struct {
	Parameters []parameterNode `yaml:"parameters"`
	Get        *operationNode  `yaml:"get"`
	Post       *operationNode  `yaml:"post"`
	Put        *operationNode  `yaml:"put"`
	Patch      *operationNode  `yaml:"patch"`
	Delete     *operationNode  `yaml:"delete"`
	Head       *operationNode  `yaml:"head"`
	Options    *operationNode  `yaml:"options"`
	Trace      *operationNode  `yaml:"trace"`
}

type operationNode struct {
	OperationID string          `yaml:"operationId"`
	Parameters  []parameterNode `yaml:"parameters"`
}

type parameterNode struct {
	Ref           string     `yaml:"$ref"`
	ComponentName string     `yaml:"-"`
	Name          string     `yaml:"name"`
	In            string     `yaml:"in"`
	Required      bool       `yaml:"required"`
	Schema        schemaNode `yaml:"schema"`
}

