func containsProblem(problems []string, substring string) bool {
	for _, problem := range problems {
		if strings.Contains(problem, substring) {
			return true
		}
	}

	return false
}

func controlSchemaTestComponents() map[string]schemaNode {
	var stringSchema, integerSchema, parentReference, parent, child schemaNode

	stringSchema.Type = schemaStringType
	integerSchema.Type = testSchemaIntegerType
	parentReference.Ref = "#/components/schemas/BaseFeatureRequest"
	parent.Type = testSchemaObjectType
	parent.Properties = map[string]schemaNode{"endpointId": stringSchema, "entityId": stringSchema}
	child.Type = testSchemaObjectType
	child.AllOf = []schemaNode{parentReference}
	child.Properties = map[string]schemaNode{"brightness": integerSchema}

	return map[string]schemaNode{"BaseFeatureRequest": parent, "BrightnessControlRequest": child}
}

func parsedTestType(t *testing.T, file *ast.File, name string) *ast.TypeSpec {
	t.Helper()

	for _, declaration := range file.Decls {
		group, ok := declaration.(*ast.GenDecl)
		if !ok {
			continue
		}

		for _, specification := range group.Specs {
			typeSpec, ok := specification.(*ast.TypeSpec)
			if ok && typeSpec.Name.Name == name {
				return typeSpec
			}
		}
	}

	t.Fatalf("parsed test source is missing type %s", name)

	return nil
}
