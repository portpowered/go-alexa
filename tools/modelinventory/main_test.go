func TestAnonymousJSONObjectIsRejected(t *testing.T) {
	t.Parallel()

	source := []byte(`package sample
func request() {
	var raw struct {
		RangeValue *struct { Value *float64 ` + "`json:\"value\"`" + ` } ` + "`json:\"rangeValue\"`" + `
	}
}
`)

	_, problems, _ := scanHandwrittenSource("pkg/request.go", source, token.NewFileSet(), false, nil)
	if !containsProblem(problems, "anonymous handwritten JSON object") {
		t.Fatalf("scanHandwrittenSource() problems = %v; want anonymous JSON object rejection", problems)
	}
}

func TestValidateEvidenceAcceptsExactReceiverSignatureReference(t *testing.T) {
	t.Parallel()

	path := writeEvidenceSource(t, `package sample
type SDKRequest struct{}
type Client struct{}
type Session struct{}
func (*Client) Convert(req SDKRequest) error { return consume(req) }
func (*Session) Convert(req string) error { return consume(req) }
`)

	err := validateEvidence(path+"#Client.Convert", "SDKRequest")
	if err != nil {
		t.Fatalf("validateEvidence() rejected production signature evidence: %v", err)
	}

	err = validateEvidence(path+"#Session.Convert", "SDKRequest")
	if err == nil {
		t.Fatal("validateEvidence() accepted a same-named method on the wrong receiver")
	}
}

func TestValidateEvidenceRejectsUnreferencedModel(t *testing.T) {
	t.Parallel()

	path := writeEvidenceSource(t, `package sample
type SDKRequest struct{}
type Client struct{}
func (*Client) Convert(value string) error { return consume(value) }
`)

	err := validateEvidence(path+"#Client.Convert", "SDKRequest")
	if err == nil {
		t.Fatal("validateEvidence() accepted a function unrelated to the listed model")
	}
}

func writeEvidenceSource(t *testing.T, source string) string {
	t.Helper()
	path := filepath.Join(t.TempDir(), "evidence.go")

	err := os.WriteFile(path, []byte(source), 0o600)
	if err != nil {
		t.Fatalf("write evidence source: %v", err)
	}

	return path
}

