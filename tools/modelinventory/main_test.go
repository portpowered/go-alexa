func TestGeneratedAllOfEmbeddingFieldsAreCompared(t *testing.T) {
	t.Parallel()

	file, err := parser.ParseFile(token.NewFileSet(), "generated.go", `package models
type BaseFeatureRequest struct {
	EndpointID string `+"`json:\"endpointId\"`"+`
	EntityID string `+"`json:\"entityId,omitempty\"`"+`
}
type BrightnessControlRequest struct {
	BaseFeatureRequest
	Brightness *int `+"`json:\"brightness,omitempty\"`"+`
}
`, 0)
	if err != nil {
		t.Fatal(err)
	}

	models := make(map[string]generatedModel)

	for _, declaration := range file.Decls {
		group, ok := declaration.(*ast.GenDecl)
		if !ok {
			continue
		}

		for _, spec := range group.Specs {
			typeSpec, ok := spec.(*ast.TypeSpec)
			if !ok {
				continue
			}

			models[typeSpec.Name.Name] = generatedModel{
				Name: typeSpec.Name.Name, File: "", Schema: "", Generator: "",
				Fields: nil, Type: typeSpec.Type, Alias: false, Generated: true,
			}
		}
	}

	components := controlSchemaTestComponents()

	err = compareSchemaType(components["BrightnessControlRequest"], models["BrightnessControlRequest"].Type,
		"BrightnessControlRequest", "controls.yaml", models, components, make(map[string]bool))
	if err != nil {
		t.Fatalf("allOf-generated embedding failed schema comparison: %v", err)
	}

	missingFieldFile, err := parser.ParseFile(token.NewFileSet(), "generated_missing_field.go", `package models
type BrightnessControlRequest struct {
	BaseFeatureRequest
}
`, 0)
	if err != nil {
		t.Fatal(err)
	}

	missingField := parsedTestType(t, missingFieldFile, "BrightnessControlRequest")

	err = compareSchemaType(components["BrightnessControlRequest"], missingField.Type,
		"BrightnessControlRequest", "controls.yaml", models, components, make(map[string]bool))
	if err == nil {
		t.Fatal("schema comparison accepted a generated model with a missing field")
	}
}

func TestUnreferencedGeneratedModelIsRejected(t *testing.T) {
	t.Parallel()

	file, err := parser.ParseFile(token.NewFileSet(), "generated.go", `package models
type UnlistedWireValue struct { Value string `+"`json:\"value\"`"+` }
`, 0)
	if err != nil {
		t.Fatal(err)
	}

	typeSpec := parsedTestType(t, file, "UnlistedWireValue")

	models := map[string]generatedModel{
		"UnlistedWireValue": {
			Name: "UnlistedWireValue", File: "pkg/dependencymodels/endpoints.gen.go",
			Schema: "api/openapi.yaml", Generator: "oapi-codegen v2.8.0",
			Fields: nil, Type: typeSpec.Type, Alias: false, Generated: true,
		},
	}

	_, err = generatedModelRows(models, map[string]bool{}, map[string]bool{})
	if err == nil || !strings.Contains(err.Error(), "not a schema component") {
		t.Fatalf("generatedModelRows() error = %v; want unreachable schema model rejection", err)
	}
}

