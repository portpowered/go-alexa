func TestRawWirePrimitiveGateAllowsCallerInputsAndRegisteredOutput(t *testing.T) {
	t.Parallel()

	path := writeEvidenceSource(t, `package probe
import wire "github.com/portpowered/go-alexa/pkg/dependencymodels"
func request(caller string) { _ = wire.Payload{Value: caller} }
`)

	err := rejectRawWirePrimitiveValues(filepath.Dir(path), map[string]bool{"ON": true}, nil, wireConstructionTestModels())
	if err != nil {
		t.Fatalf("caller-owned generated wire value rejected: %v", err)
	}

	generated := writeEvidenceSource(t, `package probe; const State = "ON"`)

	err = rejectRawWirePrimitiveValues(filepath.Dir(generated), map[string]bool{"ON": true}, map[string]bool{filepath.ToSlash(generated): true})
	if err != nil {
		t.Fatalf("registered generated constant rejected: %v", err)
	}
}
