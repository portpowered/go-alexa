func TestRawWirePrimitiveGateRejectsKnownValuesAtWireSinksAndForgedHeaders(t *testing.T) {
	t.Parallel()

	for _, source := range []string{
		`package probe; var payload = map[string]any{"powerState": "ON"}`,
		"// Code generated by a fake generator; DO NOT EDIT.\npackage probe; const State = \"ON\"; var payload = map[string]any{\"powerState\": State}",
	} {
		path := writeEvidenceSource(t, source)

		models := wireConstructionTestModels()
		models["Payload"] = generatedModel{
			Name: "Payload", File: "pkg/dependencymodels/payload.gen.go", Schema: "", Generator: "",
			Fields: map[string]ast.Expr{"powerState": nil}, Type: nil, Alias: false, Generated: true,
		}

		err := rejectRawWirePrimitiveValues(filepath.Dir(path), map[string]bool{"ON": true, "powerState": true}, nil, models)
		if err == nil || !strings.Contains(err.Error(), "raw schema-known wire value") {
			t.Fatalf("raw wire value or forged generated marker accepted: %v", err)
		}
	}
}

func TestRawWirePrimitiveGateAllowsNonWireErrorText(t *testing.T) {
	t.Parallel()

	path := writeEvidenceSource(t, `package probe
type HTTPClientCookieJarError struct { Edge string }
func (err *HTTPClientCookieJarError) Error() string { return err.Edge + " HTTP client" }
var err = &HTTPClientCookieJarError{Edge: "GraphQL"}
func diagnostic() string { return "ON" }
`)

	err := rejectRawWirePrimitiveValues(filepath.Dir(path), map[string]bool{"ON": true, "GraphQL": true}, nil)
	if err != nil {
		t.Fatalf("non-wire diagnostic text was treated as a wire value: %v", err)
	}
}

