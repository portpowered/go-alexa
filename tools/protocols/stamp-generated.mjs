import { readdir, readFile, rmdir, unlink, writeFile } from "node:fs/promises";
import { basename, join } from "node:path";
import { fileURLToPath } from "node:url";

const packageDirectory = fileURLToPath(
  new URL("../../pkg/dependencymodels/", import.meta.url),
);
const outputDirectory = join(packageDirectory, ".asyncapi-generated");
const marker = "// Code generated by Modelina. DO NOT EDIT.\n";

for (const name of await readdir(packageDirectory)) {
  if (name.startsWith("asyncapi_") && name.endsWith(".gen.go")) {
    await unlink(join(packageDirectory, name));
  }
}

for (const name of await readdir(outputDirectory)) {
  if (!name.endsWith(".go")) {
    continue;
  }

  const source = await readFile(join(outputDirectory, name), "utf8");
  const generatedName = `asyncapi_${basename(name, ".go")}.gen.go`;
  const contents = source.startsWith(marker) ? source : marker + source;
  await writeFile(join(packageDirectory, generatedName), contents);
}

for (const name of await readdir(outputDirectory)) {
  if (name.endsWith(".go")) {
    await unlink(join(outputDirectory, name));
  }
}
await rmdir(outputDirectory);
